#!/usr/bin/env node
/**
 * Build script for the PolyMate products pages.
 *
 * Single source of truth: data/products.json
 *
 * Outputs:
 *   - products/index.html        (the one and only products page: /products/)
 *   - assets/products/*.webp     (400px + 800px WebP, PNG originals are kept untouched)
 *   - assets/polymate-mark.webp  (small logo for the products page nav)
 *   - index.html                 (ONLY the block between the PRODUCTS:START / PRODUCTS:END markers)
 *   - sitemap.xml                (home, /products/, blog pages that exist)
 *
 * It never creates per-product pages.
 *
 * Usage:  node tools/build-products.mjs
 * Needs:  `sharp` (npm install in tools/, or point SHARP_DIR at a folder containing node_modules/sharp)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) => path.join(ROOT, ...p);

// ---------- load sharp ----------
let sharp;
try {
  sharp = createRequire(import.meta.url)('sharp');
} catch {
  if (!process.env.SHARP_DIR) {
    console.error('sharp not found. Run `npm install` in tools/ or set SHARP_DIR.');
    process.exit(1);
  }
  sharp = createRequire(path.join(process.env.SHARP_DIR, 'noop.js'))('sharp');
}

// ---------- helpers ----------
const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const jsonLd = (obj) => JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
const base = (src) => path.basename(src, path.extname(src));

const data = JSON.parse(fs.readFileSync(rel('data', 'products.json'), 'utf8'));
const { site, page, categories, products, comingSoon } = data;
const SITE = site.url.replace(/\/$/, '');
const PRODUCTS_URL = `${SITE}/products/`;
const SIZES = [400, 800];

// ---------- images ----------
const imgInfo = {}; // src -> { 400: {file,w,h}, 800: {...} }

async function makeVariants(src) {
  const input = rel(src);
  if (!fs.existsSync(input)) throw new Error(`Missing source image: ${src}`);
  const out = {};
  for (const w of SIZES) {
    const file = `assets/products/${base(src)}-${w}.webp`;
    const info = await sharp(input)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: 82, effort: 5 })
      .toFile(rel(file));
    out[w] = { file, w: info.width, h: info.height, bytes: info.size };
  }
  imgInfo[src] = out;
}

fs.mkdirSync(rel('assets', 'products'), { recursive: true });
const allImages = [
  ...products.flatMap((p) => p.images.map((i) => i.src)),
  ...(comingSoon ? [comingSoon.image.src] : []),
];
for (const src of new Set(allImages)) await makeVariants(src);

// small logo for the products page nav (original polymate-mark.png is ~550 KB)
await sharp(rel('polymate-mark.png'))
  .resize({ height: 104, withoutEnlargement: true })
  .webp({ quality: 85 })
  .toFile(rel('assets', 'polymate-mark.webp'));
const logoMeta = await sharp(rel('assets', 'polymate-mark.webp')).metadata();

// ---------- shared pieces ----------
const catName = Object.fromEntries(categories.map((c) => [c.id, c.name]));
const desc = (p) => `${p.name} — ${p.features.join(' / ')}`;

// ---------- homepage block ----------
function homeCard(p) {
  const v = imgInfo[p.images[0].src][400];
  const href = `/products/#${p.id}`;
  return `    <div class="product-card">
      <div class="product-img">
        <a href="${href}" tabindex="-1" aria-hidden="true"><img src="${v.file}" alt="${esc(p.images[0].alt)}" width="${v.w}" height="${v.h}" loading="lazy" decoding="async"></a>
      </div>
      <div class="product-info">
        <h4><a href="${href}">${esc(p.name)}</a></h4>
        <ul>
${p.features.map((f) => `          <li>${esc(f)}</li>`).join('\n')}
        </ul>${p.badge ? `\n        <span class="product-badge">${esc(p.badge)}</span>` : ''}
      </div>
    </div>`;
}

function comingSoonCard(c) {
  const v = imgInfo[c.image.src][400];
  return `    <div class="product-card">
      <div class="product-img">
        <img src="${v.file}" alt="${esc(c.image.alt)}" width="${v.w}" height="${v.h}" loading="lazy" decoding="async">
      </div>
      <div class="product-info">
        <h4>${esc(c.name)}</h4>
        <p>${esc(c.text)}</p>${c.badge ? `\n        <span class="product-badge">${esc(c.badge)}</span>` : ''}
      </div>
    </div>`;
}

function homeBlock() {
  return `<!-- PRODUCTS:START (generated by tools/build-products.mjs from data/products.json - do not edit by hand) -->
  <div class="products-grid">
${[...products.map(homeCard), comingSoon ? comingSoonCard(comingSoon) : ''].filter(Boolean).join('\n')}
  </div>
  <div class="products-more">
    <a href="/products/" class="btn-primary">ดูสินค้าทั้งหมด</a>
  </div>
  <!-- PRODUCTS:END -->`;
}

const START = '<!-- PRODUCTS:START';
const END = '<!-- PRODUCTS:END -->';
let home = fs.readFileSync(rel('index.html'), 'utf8');
const s = home.indexOf(START);
const e = home.indexOf(END);
if (s === -1 || e === -1 || e < s) {
  console.error('index.html is missing the PRODUCTS:START / PRODUCTS:END markers.');
  process.exit(1);
}
// keep the indentation that precedes the START marker
const lineStart = home.lastIndexOf('\n', s) + 1;
const indent = home.slice(lineStart, s);
const newHome = home.slice(0, lineStart) + indent + homeBlock().replace(/^<!--/, '<!--') + home.slice(e + END.length);
if (newHome !== home) fs.writeFileSync(rel('index.html'), newHome);

// ---------- products page ----------
function productCard(p, first) {
  const img = p.images[0];
  const v4 = imgInfo[img.src][400];
  const v8 = imgInfo[img.src][800];
  const extra = p.images.slice(1);
  return `        <article class="p-card" id="${p.id}">
          <div class="p-img">
            <img src="${v4.file.replace(/^/, '/')}" srcset="/${v4.file} ${v4.w}w, /${v8.file} ${v8.w}w" sizes="(max-width: 640px) 92vw, (max-width: 1024px) 45vw, 300px" alt="${esc(img.alt)}" width="${v4.w}" height="${v4.h}"${first ? ' fetchpriority="high"' : ' loading="lazy"'} decoding="async">
          </div>${extra.length ? `
          <div class="p-thumbs">${extra.map((x) => { const t = imgInfo[x.src][400]; return `<img src="/${t.file}" alt="${esc(x.alt)}" width="${t.w}" height="${t.h}" loading="lazy" decoding="async">`; }).join('')}</div>` : ''}
          <div class="p-body">
            <h3>${esc(p.name)}</h3>
            <ul class="p-features">
${p.features.map((f) => `              <li>${esc(f)}</li>`).join('\n')}
            </ul>${p.badge ? `\n            <span class="product-badge">${esc(p.badge)}</span>` : ''}
            <a class="btn-line" href="${esc(site.lineUrl)}" target="_blank" rel="noopener">สอบถามราคา</a>
          </div>
        </article>`;
}

let firstDone = false;
const sections = categories
  .map((c) => {
    const items = products.filter((p) => p.category === c.id);
    if (!items.length) return '';
    return `    <section class="p-section" id="${c.id}" aria-labelledby="h-${c.id}">
      <h2 id="h-${c.id}">${esc(c.name)}</h2>
      <div class="p-grid">
${items.map((p) => { const html = productCard(p, !firstDone); firstDone = true; return html; }).join('\n')}
      </div>
    </section>`;
  })
  .filter(Boolean)
  .join('\n');

const graph = [
  {
    '@type': 'LocalBusiness',
    '@id': `${SITE}/#business`,
    name: site.name,
    url: `${SITE}/`,
    telephone: site.phone,
    email: site.email,
    address: {
      '@type': 'PostalAddress',
      streetAddress: site.address.street,
      addressLocality: site.address.locality,
      postalCode: site.address.postalCode,
      addressCountry: site.address.country,
    },
    geo: { '@type': 'GeoCoordinates', latitude: site.geo.latitude, longitude: site.geo.longitude },
    sameAs: [site.lineUrl, site.facebookUrl],
  },
  {
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'หน้าแรก', item: `${SITE}/` },
      { '@type': 'ListItem', position: 2, name: 'สินค้า', item: PRODUCTS_URL },
    ],
  },
  {
    '@type': 'ItemList',
    name: page.h1,
    itemListElement: products.map((p, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      item: {
        '@type': 'Product',
        '@id': `${PRODUCTS_URL}#${p.id}`,
        name: p.name,
        url: `${PRODUCTS_URL}#${p.id}`,
        description: desc(p),
        image: p.images.map((im) => `${SITE}/${imgInfo[im.src][800].file}`),
        brand: { '@type': 'Brand', name: site.brand },
        category: catName[p.category],
      },
    })),
  },
];

const ogImage = `${SITE}/${imgInfo[products[0].images[0].src][800].file}`;
const navLink = (href, text, cur) => `<a href="${href}"${cur ? ' aria-current="page"' : ''}>${text}</a>`;
const menu = [
  ['/', 'หน้าแรก'],
  ['/#services', 'บริการ'],
  ['/products/', 'สินค้า', true],
  ['/#oem', 'OEM'],
  ['/#about', 'เกี่ยวกับเรา'],
  ['/#contact', 'ติดต่อ'],
  ['/blog/blog-index.html', 'บทความ'],
];

const productsHtml = `<!DOCTYPE html>
<html lang="th">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(page.title)}</title>
<meta name="description" content="${esc(page.description)}">
<meta name="robots" content="index, follow">
<link rel="canonical" href="${PRODUCTS_URL}">

<meta property="og:title" content="${esc(page.title)}">
<meta property="og:description" content="${esc(page.description)}">
<meta property="og:type" content="website">
<meta property="og:url" content="${PRODUCTS_URL}">
<meta property="og:image" content="${ogImage}">
<meta property="og:locale" content="th_TH">

<script type="application/ld+json">
${jsonLd({ '@context': 'https://schema.org', '@graph': graph })}
</script>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Montserrat:wght@400;600;700;800&family=Sarabun:wght@300;400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/assets/product.css">
</head>
<body>

<nav>
  <a class="nav-logo" href="/" aria-label="PolyMate Products หน้าแรก">
    <img class="nav-logo-mark" src="/assets/polymate-mark.webp" alt="PolyMate Products logo" width="${logoMeta.width}" height="${logoMeta.height}">
    <div class="nav-brand">
      <div class="nav-brand-name">POLY<em>MATE</em></div>
      <div class="nav-brand-sub">PRODUCTS CO., LTD.</div>
    </div>
  </a>
  <ul class="nav-links">
${menu.map(([h, t, c]) => `    <li>${navLink(h, t, c)}</li>`).join('\n')}
  </ul>
  <a class="nav-cta" href="/#contact">ติดต่อเรา</a>
  <button class="nav-hamburger" id="hamburger" aria-label="เปิดเมนู" aria-expanded="false" aria-controls="mobileNav">
    <span></span><span></span><span></span>
  </button>
</nav>

<div class="mobile-nav" id="mobileNav">
  <ul>
${menu.map(([h, t, c]) => `    <li>${navLink(h, t, c).replace('<a ', '<a class="mobile-link" ')}</li>`).join('\n')}
  </ul>
  <a href="/#contact" class="mobile-nav-cta mobile-link">ติดต่อเรา</a>
</div>

<main>
  <header class="page-head">
    <nav class="breadcrumb" aria-label="Breadcrumb">
      <ol>
        <li><a href="/">หน้าแรก</a></li>
        <li aria-current="page">สินค้า</li>
      </ol>
    </nav>
    <div class="section-label">สินค้าของเรา</div>
    <h1 class="section-title">${esc(page.h1)}</h1>
    <p class="section-desc">${esc(page.intro)}</p>
    <ul class="cat-jump">
${categories.map((c) => `      <li><a href="#${c.id}">${esc(c.name)}</a></li>`).join('\n')}
    </ul>
  </header>

  <div class="p-wrap">
${sections}
  </div>

  <section class="p-cta" aria-labelledby="h-cta">
    <h2 id="h-cta">สนใจสินค้า สอบถามราคาได้เลย</h2>
    <p>ติดต่อทีมขายของ Polymate Products ได้ทาง Line หรือโทรศัพท์ นอกจากสินค้าสำเร็จรูป เรายังรับ <a href="/#oem">ฉีดพลาสติกและเปิดแม่พิมพ์แบบ OEM</a> อ่านความรู้เพิ่มเติมได้ที่ <a href="/blog/blog-index.html">บทความ</a></p>
    <div class="p-cta-btns">
      <a class="btn-line" href="${esc(site.lineUrl)}" target="_blank" rel="noopener">Line ${esc(site.lineId)}</a>
      <a class="btn-tel" href="${esc(site.phoneHref)}">โทร ${esc(site.phone)}</a>
    </div>
  </section>
</main>

<footer>
  <div class="footer-inner">
    <div>
      <div class="footer-brand-name">POLY<em>MATE</em> PRODUCTS CO., LTD.</div>
      <div class="footer-tagline">YOUR PLASTIC PARTNER</div>
      <p class="footer-desc">ผู้เชี่ยวชาญด้านพลาสติกขึ้นรูป รับออกแบบแม่พิมพ์ ฉีดขึ้นรูป และจำหน่ายสินค้าพลาสติกคุณภาพ ส่งตรงจากโรงงาน</p>
    </div>
    <div class="footer-col">
      <h4>เมนู</h4>
      <ul>
${menu.map(([h, t]) => `        <li><a href="${h}">${t}</a></li>`).join('\n')}
      </ul>
    </div>
    <div class="footer-col">
      <h4>ติดต่อ</h4>
      <ul>
        <li><a href="${esc(site.phoneHref)}">${esc(site.phone)}</a></li>
        <li><a href="mailto:${esc(site.email)}">อีเมลเรา</a></li>
        <li><a href="${esc(site.lineUrl)}" target="_blank" rel="noopener">Line: ${esc(site.lineId)}</a></li>
        <li><a href="${esc(site.facebookUrl)}" target="_blank" rel="noopener">Facebook: PolyMate Products</a></li>
        <li><a href="/#contact">อ.บ้านโป่ง ราชบุรี</a></li>
      </ul>
    </div>
  </div>
  <div class="footer-bottom">
    <span>© 2025 Polymate Products Co., Ltd. All rights reserved.</span>
    <span>Designed with ❤️ in Thailand</span>
  </div>
</footer>

<script>
const hamburger = document.getElementById('hamburger');
const mobileNav = document.getElementById('mobileNav');
hamburger.addEventListener('click', () => {
  const open = hamburger.classList.toggle('open');
  mobileNav.classList.toggle('open', open);
  hamburger.setAttribute('aria-expanded', String(open));
});
</script>
</body>
</html>
`;

fs.mkdirSync(rel('products'), { recursive: true });
fs.writeFileSync(rel('products', 'index.html'), productsHtml);

// ---------- sitemap ----------
const day = (f) => fs.statSync(f).mtime.toISOString().slice(0, 10);
const urls = [
  { loc: `${SITE}/`, file: rel('index.html') },
  { loc: PRODUCTS_URL, file: rel('products', 'index.html') },
  ...fs
    .readdirSync(rel('blog'))
    .filter((f) => f.endsWith('.html'))
    .sort()
    .map((f) => ({ loc: `${SITE}/blog/${f}`, file: rel('blog', f) })),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url>\n    <loc>${u.loc}</loc>\n    <lastmod>${day(u.file)}</lastmod>\n  </url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(rel('sitemap.xml'), sitemap);

// ---------- report ----------
console.log('Built:');
for (const [src, v] of Object.entries(imgInfo))
  console.log(`  ${src}  ->  ${SIZES.map((w) => `${w}px ${(v[w].bytes / 1024).toFixed(0)}KB`).join(', ')}`);
console.log(`  products/index.html, sitemap.xml (${urls.length} urls), homepage block updated`);
